def s(doc, a, b, note="", role="main"):
    return {"doc": doc, "pages": [a, b], "note": note, "role": role}


def sup(doc, a, b, note=""):
    return s(doc, a, b, note, "supp")


def ref(doc, a, b, note):
    """An analysis reference: not taught as lesson material. The tutor uses it to carry the
    module's result to an operational outcome (and the learner designs the analysis)."""
    return {"doc": doc, "pages": [a, b], "note": note, "role": "ref"}


def art(doc, note="", a=None, b=None):
    """An article or report: the whole document, or the pages a, b when only part of it is taught."""
    return {"doc": doc, "pages": None if a is None else [a, b], "note": note, "role": "article"}


TRIM = "עיון: שאר הדוח. לא חומר שיעור; זמין לקריאה לפי הצורך (קיצור שאושר ב-6.11)"


def cut(doc, total, keep, rest=TRIM):
    """A long report that is taught only in part: the kept ranges (a, b, note) are taught as an
    article, and every other page of the document stays in the module as reading (role ref)."""
    out = [art(doc, note, a, b) for a, b, note in keep]
    p = 1
    for a, b, _ in sorted(keep):
        if a > p:
            out.append(ref(doc, p, a - 1, rest))
        p = b + 1
    if p <= total:
        out.append(ref(doc, p, total, rest))
    return out


