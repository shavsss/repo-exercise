const go = (n) => `__go(${n})`;
const after = (ms, js) => `setTimeout(()=>{${js}},${ms})`;
const P = (sel) => `document.querySelector(${JSON.stringify(sel)})`;
const consult = (side) => `__go(2);` + after(120, `const p=document.querySelector("#p${side} p[data-b]");openConsult(p,p.textContent.slice(0,80),0)`);
const L = [];
const add = (id, v, o = {}) => L.push(Object.assign({ name: `${id}-${v}`, q: `${id}=${v}&open=none` }, o));
for (const v of ["frank", "david", "noto"]) add("face", v, { js: go(2) });
for (const v of ["justify", "start", "space"]) add("align", v, { js: go(2) });
for (const v of ["classic", "center", "hebrew"]) add("head", v, { js: go(2) });
for (const v of ["smooth", "fiber", "lab"]) add("paper", v, { js: go(2) });
for (const v of ["graphite", "lamp", "ink"]) add("dark", v, { js: go(2), dark: true });
for (const v of ["flat", "gutter", "lamp"]) add("light", v, { js: go(2) });
for (const v of ["curl", "rigid"]) add("turn", v, { q: `turn=${v}&speed=s900&open=none`, js: go(2) + ";" + after(60, `document.getElementById("next").click()`), wait: 430 });
add("turn", "slide", { q: "turn=slide&open=none", js: go(2) + ";" + after(60, `document.getElementById("next").click()`), wait: 130 });
add("turn", "none", { js: go(4) });
add("open", "book", { q: "open=book", wait: 0, settle: 1050 });
