const conf = after(150, `${P("[data-act=conf][data-v=fair]")}.click()`);
add("think", "flap", { js: go(2) + ";" + conf, wait: 900 });
add("think", "back", { js: go(4), wait: 500 });
add("think", "margin", { js: go(2) + ";" + conf, wait: 700 });
add("consult", "slip", { js: consult("R"), wait: 600 });
add("consult", "margin", { js: consult("R"), wait: 600, vp: { width: 1920, height: 1080 } });
add("consult", "facing", { js: consult("R"), wait: 600 });
add("scene", "plate", { js: go(4) + ";" + after(150, `${P("[data-act=lift]")}.click()`), wait: 900 });
add("scene", "spread", { js: go(4) + ";" + after(150, `${P("[data-act=lift]")}.click()`), wait: 900 });
add("scene", "live", { js: go(4), wait: 500 });
add("figure", "inline", { js: go(4) });
add("figure", "page", { js: go(4) });
add("figure", "spread", { js: go(4) });
add("nav", "ribbon", { js: go(4) + ";" + after(150, `${P(".ribbon")}.click()`), wait: 600 });
add("nav", "tabs", { js: go(4) });
add("nav", "drawer", { js: go(4) + ";" + after(150, `${P("[data-act=drawer]")}.click()`), wait: 700 });
add("eqref", "margin", { js: go(6) });
add("eqref", "none", { js: go(6) });
for (const v of ["facing", "side", "bottom"]) add("scratch", v, { js: go(2) + ";" + after(150, `document.getElementById("scratchBtn").click()`), wait: 700, vp: v === "side" ? { width: 1920, height: 1080 } : undefined });
add("stream", "fill", { js: go(4) + ";" + after(100, `document.getElementById("streamBtn").click()`), wait: 3800 });
add("stream", "whole", { js: go(4) + ";" + after(100, `document.getElementById("streamBtn").click()`), wait: 3800 });
add("frame", "laptop", { vp: { width: 1366, height: 680 }, js: go(2) });
add("frame", "big", { vp: { width: 1920, height: 1040 }, js: go(2) });
add("phone", "light", { vp: { width: 400, height: 820 }, js: go(3) });
